function renderEntry(command, content, promptText) {
  const entry = document.createElement('div');
  entry.className = 'entry';

  const promptLine = document.createElement('div');
  promptLine.className = 'prompt-line';
  promptLine.innerHTML = '<span class="prompt-symbol"></span><span class="typed"></span>';
  promptLine.querySelector('.prompt-symbol').textContent = promptText || getPromptText();
  promptLine.querySelector('.typed').textContent = command;

  const outputEl = document.createElement('div');
  outputEl.className = 'output' + (content.isError ? ' error' : '');
  if (content.html) {
    outputEl.innerHTML = content.html;
  } else {
    outputEl.textContent = content.text;
  }

  entry.appendChild(promptLine);
  entry.appendChild(outputEl);

  if (content.ascii) {
    const asciiWrap = document.createElement('div');
    asciiWrap.className = 'ascii-wrap';
    const asciiEl = document.createElement('pre');
    asciiEl.className = 'ascii-block';
    asciiEl.textContent = content.ascii;
    asciiWrap.appendChild(asciiEl);
    entry.appendChild(asciiWrap);
  }

  history.appendChild(entry);
  scrollToBottom();
}

function runCommand(raw) {
  const cmd = raw.trim();
  if (!cmd) return;

  commandLog.push(cmd);
  logIndex = commandLog.length;

  const promptText = getPromptText();

  if (cmd === 'clear') {
    history.innerHTML = '';
    return;
  }

  const parts = cmd.split(/\s+/);
  const key = parts[0].toLowerCase();
  const args = parts.slice(1);

  if (COMMANDS[key]) {
    const result = COMMANDS[key](args);
    if (typeof result === 'string') {
      renderEntry(cmd, { text: result }, promptText);
    } else {
      renderEntry(cmd, result, promptText);
    }
  } else {
    renderEntry(
      cmd,
      { text: `command not found: ${cmd}\ntype 'help' for a list of commands`, isError: true },
      promptText
    );
  }
}

